# ###############################################
# ### SETUP ###
import turtle
# ###############################################

t = turtle.Turtle()
t.penup()
t.goto(-100, -100)
t.color("red")
t.pendown()

for i in range(5):
    t.forward(72)
    t.left(216)


# ###############################################
# ### ENDING ###
turtle.exitonclick()
